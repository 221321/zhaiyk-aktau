// Разовый скрипт очистки тестовых остатков, введённых вручную до
// восстановления синхронизации остатков из 1С. Удаляет ВСЕ записи из
// stock (кол-во коробов и вес в кг обнуляются для всех кодов) — следующая
// же синхронизация из 1С ("Синхронизировать остатки" в 1С) заполнит их
// заново реальными данными.
//
// НЕ трогает: пользователей, псевдонимы товаров (productAliases,
// в т.ч. флаг "Весовой товар" и средний вес короба), номенклатуру
// (products), заявки и остальные коллекции — только остатки.
//
// ВАЖНО:
//   1) Перед запуском останови сервер (pm2 stop zhaiyk-aktau), иначе можно
//      потерять запись, если сервер в этот момент тоже пишет в db.json.
//   2) Сначала сделай бэкап: ./scripts/backup-db.sh
//   3) По умолчанию скрипт ничего не удаляет — только показывает, сколько
//      кодов найдено. Для реального удаления нужен флаг --confirm.
//   4) После скрипта запусти сервер обратно (pm2 start zhaiyk-aktau) и
//      сразу синхронизируй остатки из 1С, иначе каталог будет показывать
//      "нет в наличии" по всем товарам до следующей синхронизации.
//
// Использование:
//   ./scripts/backup-db.sh
//   node scripts/cleanup-test-stock.js            # dry-run, ничего не меняет
//   node scripts/cleanup-test-stock.js --confirm  # реальное удаление

const low = require('lowdb');
const FileSync = require('lowdb/adapters/FileSync');

const db = low(new FileSync('db.json'));

const stock = db.get('stock').value() || [];
console.log(`Найдено записей остатков в базе: ${stock.length}`);

if (stock.length === 0) {
  console.log('Остатков нет, очищать нечего.');
  process.exit(0);
}

if (!process.argv.includes('--confirm')) {
  console.log('');
  console.log('Это ПОЛНОСТЬЮ и БЕЗВОЗВРАТНО удалит все остатки выше (заявки,');
  console.log('пользователи и псевдонимы товаров затронуты не будут).');
  console.log('Убедись, что бэкап уже сделан (./scripts/backup-db.sh), и запусти:');
  console.log('  node scripts/cleanup-test-stock.js --confirm');
  process.exit(0);
}

db.set('stock', []).write();

console.log(`Удалено записей остатков: ${stock.length}`);
console.log('Заявки, пользователи, роли, пароли, псевдонимы товаров не затронуты.');
console.log('Теперь запусти сервер обратно и синхронизируй остатки из 1С.');
